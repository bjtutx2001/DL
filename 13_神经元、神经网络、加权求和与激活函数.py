"""
神经网络有多个层组成：输入层（1层），隐藏层（多层），输出层（1层）
每层的输入是前一层的输出
从数学多角度，每一层神经网络包括加权求和与激活函数两步，但在pytorch中视为为两层
并不一定要求每一层都要加权和激活，只是通常会两步都包括
常见的激活函数有Sigmoid、Tanh、ReLu、SoftMax
    1、Sigmoid=1/(1+e^-x),取值范围(0,1),x就是加权求和的结果，对于sigmoid，输入值在[-6,6]差异明显，在[-3,3]效果明显，sigmoid通常在5层内会产生梯度消失现象，一般用于二分类，用于输出层
    2、Tanh=(1-e^-2x)/(1+e^-2x),取值范围(-1,1),[-3,3]之间差异明显,[-1,1]之间效果明显，多用于隐藏层
    3、ReLu：负数变0，正数不变，即只考虑正样本，还有个LeakyReLu，可考虑正负样本，负数变为0.01倍，正数不变
    4、SoftMax=e^xi/(Σe^xi)，即当前分类预测概率为当前分类预测分数的指数运算除以所有分类预测分数的指数运算之和，由用于多分类
激活函数的选择方法：
    1、隐藏层：默认先用 ReLU
    2、输出层：由任务决定
"""