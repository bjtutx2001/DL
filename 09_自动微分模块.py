"""
自动微分模块：
    作用：对损失函数求导，结合反向传播，自动更新权重参数w，b
    损失函数：基于误差，将误差转换为一个可以用于优化模型参数的数值，常见的有均方误差，均方根误差，平均绝对误差，损失函数通常为关于权重的函数
    损失函数求导就是梯度，自动微分模块就是计算的这个
    y=kx+b，k为权重，b为偏置，得到的y为预测值，根据预测值和实际值求出误差，选取适当的损失函数描述误差
    对损失函数求导得到梯度g，根据梯度下降：w‘=w-a*g，a为学习率，更新权重，实际开发通常将偏置矩阵设为全0

案例：演示自动微分模块

"""
import torch

#设置权重参数
w=torch.tensor([1,2,3],requires_grad=True,dtype=torch.float)    #参数2：指定需要自动微分，参数3：自动微分需要float数据类型
#设置损失函数，也叫前向计算
loss=2*w**2                 #这里损失函数关于不同的权重的函数关系设置成一样，是为了方便学习，实际关于不同的权重的表现形式是不一样的
#反向传播
# print(loss.sum())
loss.sum().backward()       #这里由于有多个权重，需要进行求和才能进行求梯度，设三个权重为w1,w2，w3，如果直接指定loss进行反向传播进行微分计算
                            #相当对loss是一个向量loss=[w1²，w2²，w3²]，进行求导，没有指定对哪一个，而求和之后，loss会变成loss=w1²+w2²+w3²
                            #就能对三个变量求导了
#获取梯度
print(w.grad)               #梯度默认会累加

