"""
演示张量的索引操作
"""
import torch
torch.manual_seed(37)       #随机种子

a=torch.randint(1,50,(5,5))
print(a)
#简单行列索引。左行右列，和列表类似
print(a[0])     #获取第一行数据
print(a[1,:])   #获取第二行数据
print(a[:,3])   #第三列

#列表索引，前边表示行，后边表示列
#单独取，用，
print(a[[1,2],[2,3]])   #[1,2]为行索引，[2,3]为列索引，表示2行3列和3行4类的元素
#范围取演示
print(a[[1,2,3]][:,[3,4]])    #先取2,3,4行，再取2,3,4行的4,5列
print(a[1:3,2:4])           #先取2到4行，再取3到5列
print(a[1:3,2])           #先取2到4行，再取3列
print(a[1:3,[2,4]])           #先取2到4行，再取2和4列

#范围索引

print(a[:3,:2])         #前3行，前2列
print(a[1:,:2])            #第二行到最后一行，前两列
print(a[::2,1::2])        #所有奇数行，偶数列,起始位置：结束位置：步长。遵循左闭右开

#布尔索引
#第3列大于5的数据,多种理解
print(a)
print(a[a[:,2]>5])  #第3列数值大于5的所有行数据
print(a[:,a[:,2]>5])  #a[:,[1,1,1,1,0]] 前四列

#第二行大于5的所有列数据数据，实际上是要满足条件的列，即所有行都要
print(a[:,a[1,:]>5])
#只要第二行大于10的行数据
print(a[1,a[1,:]>10])

#多维索引
b=torch.randint(1,50,(2,2,3))       #两个2行3列
print(b)
print(b[:,:,1])     #获取2轴第2个数据
print(b[:,1,:])     #获取1轴第2个元素
print(b[1,:,:])     #获取0轴第2个元素