"""
循环层:是循环神经网络（RNN）的核心部分，其主要作用是按照序列顺序逐步处理输入数据，并通过隐藏状态将前面时间步的信息传递给后面的时间步。
隐藏状态（Hidden State）的主要作用是保存前面时间步提取的信息，并将这些信息传递给后面的时间步，使网络能够学习序列数据中的前后依赖关系。
循环层的计算：
    循环层的一个神经元通常包含两个输入（上一个时间步的输出和隐藏状态）1个输出（当前时间步的、隐藏状态），最开始的隐藏状态初始化为0
    隐藏状态计算公式：
        ht=tanh(w1*xt+w2*ht’+b)
        ht表示输出隐藏状态（当前时刻隐藏状态）
        w1，w2表示与输入与输入隐藏状态相乘的权重
        b表示偏置
        ht'表示输入隐藏状态（上一时刻隐藏状态）
        tanh为激活函数：tanh(x)=(1-e^-2x)/(1+e^-2x)
循环层的输出是一个向量，该向量经过全连接层后输出得到最终预测结果y_pred，y_pred中每个元素代表当前时刻生成词汇表中的某个词的得分，
词汇表有多少个词，y_pred就有多少个元素，最大元素值对应的词就是当前时刻预测生成的词
全连接层和输出层输出的计算：
    yt=w3*ht+b
    w3：与当前时刻隐藏状态相乘的权重
    ht：当前时刻隐藏状态
    b：偏置


"""
import torch
import torch.nn as nn

#创建循环网络层
#参数1：输入维度（词向量维度），参数2：输出隐藏状态维度，参数3：循环层层数，参数4：激活函数，参数5：是否启动双向rnn，启动了就会将序列的正向和反向分别输入rnn生成两组数据
rnn=nn.RNN(input_size=128,hidden_size=256,num_layers=1,nonlinearity='tanh',bidirectional=False)

#定义变量，表示输入的x
#每个句子5歌词，有32个句子（batch_size），每个词向量有128个维度    这是默认维度
#如果创建RNN时指定batch_first=True,就得交换第0维和第1维了
x=torch.randn(size=(5,32,128))

#定义变量，记录上一时刻的隐藏状态
#1层循环层，32个句子，隐藏状态维度为256
h0=torch.randn(size=(1,32,256))

#调用RNN
#output记录的是最后一层RNN在每一个时间步产生的隐藏状态，h1记录的是每一层RNN在最后一个时间步产生的隐藏状态
output,h1=rnn(x,h0)
print(output.shape)     #[5,32,256]
print(h1.shape)         #[1,32,256]